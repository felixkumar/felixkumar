    def prepare_updated_price_list_and_update_in_walmart(self, instance_id, walmart_products,
                                                         walmart_log_line_obj):
        """
        This method is used to Prepare Product Price List and Update in Walmart.
        @param: Walmart Instance and Walmart Products List in Pass .
        @return: True
        """
        updated_price_list = []
        price_list = instance_id and instance_id.pricelist_id
        log_lines = []
        feed_histories = []

        for wprod in range(0, len(walmart_products), 2):
            products = walmart_products[wprod:wprod + 2]

            for walmart_product_id in products:
                product_price = price_list._get_product_price(walmart_product_id.product_id, 1.0)
                updated_price_list += [
                    {"sku": walmart_product_id.walmart_sku,
                     "currentCurrency": price_list.currency_id.name,
                     "currentPrice": str(product_price),
                     }]
            feed_history, log_line = self.update_prices_in_walmart(instance_id, updated_price_list, walmart_log_line_obj)
            log_lines.append(log_line)
            feed_histories.append(feed_history)
        return feed_histories, log_lines

    def update_prices_in_walmart(self, instance_id, updated_price_list, walmart_log_line_obj):
        """
        This method is used to Update price in Walmart.
        @param: Walmart Instance and Walmart Products List in Pass .
        @return: True
        """
        walmart_feed_history_obj = self.env['walmart.feed.history.ept']
        walmart_conn_obj = instance_id.get_walmart_connection()
        log_line_id = False
        feed_history_id = False
        if updated_price_list:
            try:
                response = walmart_conn_obj.prices.bulk_update(items=updated_price_list)
                if not response or not response.get('feedId', False):
                    log_line_id = walmart_log_line_obj.create_common_log_line_ept(
                        message='Feed Submission id not found from Walmart Response while exporting price...!',
                        module='walmart_ept', res_id=False, walmart_marketplace_id=instance_id.id,
                        model_name=self._name, log_line_type='fail', mismatch_details=False,
                        operation_type="export")
                    log_line_id = log_line_id.id
                else:
                    feed_id = response.get('feedId', '').strip()
                    _logger.info(response)
                    if feed_id:
                        feed_history_id = walmart_feed_history_obj.create(
                            {'feed_id': feed_id, 'marketplace_id': instance_id.id})
                        feed_history_id = feed_history_id.id

            except Exception as err:
                raise ValidationError(str(err))
        return feed_history_id, log_line_id

