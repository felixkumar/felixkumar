    def process_offer_data(self, response, instance, log_book_id):
        """
        This method processes the data imported from Walmart and Syncs offers with Odoo Product.
        @author: Nikul Alagiya on Date 13/01/2022.
        """
        log_line_vals = []
        offer_data = response.get("ItemResponse", [])

        for data in offer_data:
            sku = data.get("sku")
            price = data.get("price", {})
            amount = price.get("amount", 0.0)
            name = data.get("productName", sku)

            _logger.info("Started processing the Offer: %s - %s" % (sku, name))

            offer_vals = self.prepare_offer_vals(data, instance)

            walmart_offer, odoo_product = self.search_walmart_offer_odoo_product(
                sku, instance)
            if walmart_offer:
                walmart_offer.write(offer_vals)
                _logger.info("Offer Updated: %s", name)
            elif odoo_product:
                offer_vals.update(
                    {"name": odoo_product.name, "product_id": odoo_product.id})
                walmart_offer = self.create(offer_vals)
                _logger.info("Offer Created: %s", name)
            else:
                self.env['common.log.lines.ept'].create_log_lines(
                    model_id=log_book_id.model_id.id,
                    res_id=False,
                    message="Offer not found",
                    default_code=sku,
                    log_book_id=log_book_id
                )
                continue
            if walmart_offer:
                pricelist_id = instance.pricelist_id
                if pricelist_id:
                    pricelist_id.set_product_price_ept(
                        walmart_offer.product_id.id, pricelist_id.id, amount)
            _logger.info("Processed the Offer: %s - %s" % (sku, name))

        return log_line_vals

    def export_stock_in_walmart(self, instance_id, walmart_products=False):
        """
        This method is used to Export Stock in Walmart.
        @param: Walmart Instance and Walmart Products List if Pass.
        @return: True
        @author: Nikul Alagiya on dated 19/01/2022
        """
        product_product_obj = self.env['product.product']
        walmart_instance_obj = self.env['walmart.marketplace.ept']
        walmart_log_line_obj = self.env['common.log.lines.ept']
        all_log_lines = []
        if not instance_id:
            instance_id = walmart_instance_obj.search([], order='id',limit=1)

        if not instance_id:
            log_line = walmart_log_line_obj.create_common_log_line_ept(
                message="Please, Select Walmart Marketplace to continue!", module='walmart_ept',
                res_id=False, walmart_marketplace_id=instance_id.id, model_name=self._name,
                log_line_type='fail', mismatch_details=True, operation_type="export")
            all_log_lines.append(log_line.id)
            return [], all_log_lines

        if walmart_products:
            odoo_products = walmart_products.mapped('product_id').ids
        else:
            last_update_date = instance_id.last_inventory_export_date or \
                               (datetime.now() - timedelta(30))
            odoo_products = product_product_obj.get_products_based_on_movement_date_ept(
                last_update_date, instance_id.company_id)
            walmart_products = self.search([
                ('product_id', '=', odoo_products), ('marketplace_id', '=', instance_id.id)])

        if not walmart_products:
            if odoo_products:
                log_line_type='fail'
                mismatch = True
                message = "There are no Walmart offers available, please import(sync) a Walmart offer first!"

            else:
                log_line_type = 'success'
                mismatch = False
                message = "Since the last export, no stock movements have been made !"
            log_line = walmart_log_line_obj.create_common_log_line_ept(
                message=message, module='walmart_ept', res_id=False, walmart_marketplace_id=instance_id.id,
                model_name=self._name, log_line_type=log_line_type, mismatch_details=mismatch, operation_type="export")
            all_log_lines.append(log_line.id)
            return [], all_log_lines

        inventory_list = self.prepare_inventory_list(instance_id, product_product_obj, odoo_products, walmart_products)
        feed_histories, log_lines = self.update_stock_in_walmart(inventory_list, instance_id)
        all_log_lines.extend(log_lines)
        instance_id.write({'last_inventory_export_date': datetime.now()})
        return feed_histories, all_log_lines

    def import_wfs_inventory(self, instance_id, auto_apply_adjustments):
        """
        This method is used to Import WFS Inventory in Walmart.
        :param instance_id: Walmart Instance
        :param auto_apply_adjustments: True or False
        :return: True
        """
        inventory_name = "Walmart%s_%s" % (instance_id.name, datetime.now().strftime("%d-%m-%Y"))
        products_stock = self.wfs_inventory_prepare_data_and_import_stock(instance_id)
        if products_stock:
            self.env['stock.quant'].create_inventory_adjustment_ept(products_stock,
                                                                    instance_id.wfs_warehouse_id.lot_stock_id,
                                                                    auto_apply_adjustments,
                                                                    inventory_name)
            instance_id.write({'last_wfs_inventory_import_date': datetime.now()})
            _logger.info("Going for the create inventory adjustment....")
        return True

    def wfs_inventory_prepare_data_and_import_stock(self, instance_id):
        """
        This method is used to prepare data and Import WFS Inventory in Walmart.
        :param instance_id: Walmart Instance
        :return: {}
        """
        walmart_offer_obj = self.env['walmart.offer.ept']
        products_stock = {}
        duplicate_walmart_product = []
        walmart_products = walmart_offer_obj.search([('exported_in_walmart', '=', True),
                                                     ('marketplace_id', '=', instance_id.id),
                                                     ('fulfillment_by', 'in', ['Walmart Fulfilled', 'WFS Eligible'])])
        # walmart_products = walmart_offer_obj.search([('marketplace_id', '=', instance_id.id)])
        sku = walmart_products.mapped('walmart_sku')
        for sku_chunk in split_every(1, sku):
            response = self.wfs_inventory_request_for_import_stock(sku_chunk, instance_id)
            if isinstance(response, str) or isinstance(response, list):
                continue
            products_stock, duplicate_walmart_product = self.prepare_wfs_inventory_data_for_inventory_adjustment(
                walmart_products, response, duplicate_walmart_product, products_stock)
            self._cr.commit()
        return products_stock

    def wfs_inventory_request_for_import_stock(self, sku_chunk, instance):
        """
        This method is used to call api and get response.
        :param sku_chunk: product sku
        :param instance: Walmart Instance
        :return: product response form walmart
        """
        log_line_obj = self.env['common.log.lines.ept']
        product_response = {}
        if instance.last_wfs_inventory_import_date:
            start_date = (instance.last_wfs_inventory_import_date - timedelta(days=1))
        else:
            today = date.today()
            start_date = (today - timedelta(days=30))
        try:
            walmart_conn_obj = instance.get_walmart_connection()
            str_sku = ",".join(sku_chunk)
            response = walmart_conn_obj.inventory.get_wfs_inventory(sku=str_sku)
            if not response:
                message = "Import WFS Inventory has not proper Response"
                _logger.info(message)
                log_line_obj.create_common_log_line_ept(message=message, model_name='walmart.offer.ept',
                                                        module='walmart_ept', operation_type='import', res_id=self.id)
            product_response = response
        except Exception as error:
            message = "Import WFS Inventory for products not perform"
            _logger.info(message)
            log_line_obj.create_common_log_line_ept(message=message, model_name='walmart.offer.ept',
                                                    module='walmart_ept', operation_type='import', res_id=self.id)
        return product_response

    def prepare_wfs_inventory_data_for_inventory_adjustment(self, walmart_products, response,
                                                            duplicate_walmart_product, products_stock):
        """
        This method is used to Prepare data for inventory adjustment.
        :param walmart_products: list of walmart products
        :param res_product: response of product
        :param duplicate_walmart_product: list of duplicate products
        :param products_stock: dict {}
        :return: dict {}
        """
        log_line_obj = self.env['common.log.lines.ept']
        qty = response.get('quantity', {}).get('amount')
        product = walmart_products.filtered(lambda x: x.walmart_sku == response.get('sku'))[0]
        if product.product_id.id not in duplicate_walmart_product:
            _logger.info("Adding qty for inventory adjustment of Walmart product: %s for ", product.product_id)
            products_stock.update({product.product_id.id: qty})
            duplicate_walmart_product.append(product.product_id.id)
        else:
            msg = "Duplicate product found in WooCommerce store with SKU: %s " % product.walmart_sku
            _logger.info(msg)
            log_line_obj.create_common_log_line_ept(message=msg, model_name='walmart.offer.ept',
                                                    default_code=product.walmart_sku,
                                                    module='walmart_ept', operation_type='import', res_id=self.id)
        return products_stock, duplicate_walmart_product

    def update_stock_in_walmart(self, inventory_list, instance_id):
        """
        This method is used to Export Stock in Walmart.
        @param: inventory_list and instance_id.
        @author: Nikul Alagiya on dated 19/01/2022
        """
        walmart_feed_history_obj = self.env['walmart.feed.history.ept']
        walmart_log_line_obj = self.env['common.log.lines.ept']
        walmart_conn_obj = instance_id.get_walmart_connection()
        feed_histories = []
        log_lines = []
        if inventory_list:
            try:
                response = walmart_conn_obj.inventory.bulk_update(items=inventory_list)
                if not response or not response.get('feedId', False):
                    message = 'Feed Submission id not found from Walmart Response...!'
                    log_line = walmart_log_line_obj.create_common_log_line_ept(
                        message=message, module='walmart_ept', model_name=self._name,
                        res_id=False, walmart_marketplace_id=instance_id.id,
                        log_line_type='fail', mismatch_details=True, operation_type="export")
                    log_lines.append(log_line.id)
                else:
                    feed_id = response.get("feedId", False)
                    if feed_id:
                        feed_history = walmart_feed_history_obj.create(
                            {'feed_id': feed_id, 'marketplace_id': instance_id.id})
                        feed_histories.append(feed_history)

            except Exception as err:
                raise ValidationError(str(err))
        return feed_histories, log_lines

    def prepare_inventory_list(self, instance_id, product_product_obj,
                               odoo_products, walmart_products=False):
        """
        This method is used to Prepare inventory list.
        @param:  instance_id, product_product_obj, odoo_products, walmart_products.
        @author: Nikul Alagiya on dated 19/01/2022
        """
        inventory_list = []
        product_stock_details = {}
        if instance_id.stock_field_id.name == 'free_qty':
            product_stock_details = product_product_obj.get_free_qty_ept(instance_id.warehouse_id, odoo_products)
        elif instance_id.stock_field_id.name == 'virtual_available':
            product_stock_details = product_product_obj.get_forecasted_qty_ept(instance_id.warehouse_id, odoo_products)
        elif instance_id.stock_field_id.name == 'qty_available':
            product_stock_details = product_product_obj.get_onhand_qty_ept(instance_id.warehouse_id, odoo_products)

        if not product_stock_details:
            return False

        for item in walmart_products:
            walmart_product_stock = product_stock_details.get(
                item.product_id.id, 0.0)
            stock = self.stock_calculation_ept(walmart_product_stock, item.offer_fix_stock_type,
                                               item.offer_fix_stock_value)

            inventory_list += [{"sku": item.walmart_sku, "quantity": str(stock)}]

        return inventory_list

    def stock_calculation_ept(self, actual_stock, fix_stock_type=False, fix_stock_value=0):
        """
        This method relocates calculate stock.
        :param actual_stock: This arguments relocates actual stock.
        :param fix_stock_type: This arguments relocates type of stock type.
        :param fix_stock_value: This arguments relocates value of stock value.
        :return: actual_stock
        """
        if actual_stock >= 1.00:
            if fix_stock_type == 'fix':
                if fix_stock_value >= actual_stock:
                    return actual_stock
                else:
                    return fix_stock_value

            elif fix_stock_type == 'percentage':
                quantity = int((actual_stock * fix_stock_value) / 100.0)
                if quantity >= actual_stock:
                    return actual_stock
                else:
                    return quantity
        return actual_stock

