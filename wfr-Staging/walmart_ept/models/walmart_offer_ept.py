    def prepare_offer_vals(self, data, instance):
        """
        This method  prepares vals to create a offer from data.
        """
        product_type_id = self.env['walmart.product.type.ept']
        product_type = data.get("productType") and data.get("productType").strip()
        if product_type:
            product_type_id = product_type_id.search([('name', '=ilike', product_type)])
            if not product_type_id:
                product_type_id = product_type_id.create({'name': product_type})
        return {"walmart_sku": data.get("sku"),
                "product_category": product_type_id.id,
                "marketplace_id": instance.id,
                "gtin": data.get("gtin", ""),
                "wpid": data.get("wpid", ""),
                "upc": data.get("upc", ""),
                "product_name": data.get("productName"),
                "fulfillment_by": data.get('Fulfillment Type'),
                "state": data.get('publishedStatus'),
                "walmart_product_lifecycle_status": data.get('lifecycleStatus'),
                "exported_in_walmart": True
                }

    def search_walmart_offer_odoo_product(self, sku, instance):
        """
        This method searches for the Walmart offer first,
        if offer not found than searches for the Odoo product.
        """
        odoo_product = self.env["product.product"]
        walmart_offer = self.search([("walmart_sku", "=", sku),
                                     ("marketplace_id", "=", instance.id)], limit=1)
        if not walmart_offer:
            odoo_product = odoo_product.search([("default_code", "=", sku)], limit=1)
        else:
            odoo_product = walmart_offer.product_id
        return walmart_offer, odoo_product
